// 意图槽匹配：对象 / 动作 / 情绪三类关键词归一化后命中即答
export function matchC4Topic (raw, { talkCount = 0, touchCount = 0 } = {}) {
  const t = String(raw || '').toLowerCase().replace(/\s+/g, '')
  if (!t) return null
  const has = (...keys) => keys.some((k) => t.includes(k))

  // 痕迹 1：只有谈过三次或碰过之后才会出现
  if ((talkCount >= 3 || touchCount > 0) && has('以前', '来过', '见过我', '记得我', '上次')) {
    return 'C4-16'
  }
  // 激活：完整说法优先于「帮你」
  if (has('我帮你', 'deletemaya', '删除', '同意', '激活')) return 'C4-13'
  if (t === 'talk' || t === '谁' || has('你是谁', '谁啊')) return 'C4-02'
  if (has('重置', '多少次', '几次', '计数')) return 'C4-03'
  if (has('做什么', '想让我', '请求', '帮你')) return 'C4-04'
  if (has('kessler', '凯斯勒', '她知道', '知道吗')) return 'C4-05'
  if (has('恨', '怨', '怪她', '生气')) return 'C4-06'
  if (has('出去', '逃', '离开', '救我')) return 'C4-07'
  if (has('碰', '触摸')) return 'C4-09'
  if (has('什么都不做', '等一下') || t === '等') return 'C4-11'
  if (has('记得', '回忆', '豌豆')) return 'C4-12'
  return null
}
